// Builds the text pages (about/, contact/, privacy/) from the same Markdown
// that agents get (agent/pages.js), so the HTML and Markdown versions never
// drift apart. Run after editing agent/pages.js:
//   node scripts/build-pages.mjs          write the pages
//   node scripts/build-pages.mjs --check  exit 1 if a page is out of date (qa)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PAGES } from "../agent/pages.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://cards.notalucis.com";
const TITLES = { "/about": "About", "/contact": "Contact", "/privacy": "Privacy" };

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function inline(text) {
  const out = [];
  // Tokens: [label](url), `code`, **bold**, bare URLs, email addresses.
  const re = /\[([^\]]+)\]\(([^)\s]+)\)|`([^`]+)`|\*\*([^*]+)\*\*|(https?:\/\/[^\s)]+[^\s).,;:])|([\w.+-]+@[\w-]+\.[\w.]+[\w])/g;
  let last = 0, m;
  while ((m = re.exec(text))) {
    out.push(esc(text.slice(last, m.index)));
    if (m[1]) out.push(`<a href="${esc(link(m[2]))}">${inline(m[1])}</a>`);
    else if (m[3]) out.push(`<code>${esc(m[3])}</code>`);
    else if (m[4]) out.push(`<strong>${inline(m[4])}</strong>`);
    else if (m[5]) out.push(`<a href="${esc(link(m[5]))}">${esc(m[5].replace(/^https?:\/\//, ""))}</a>`);
    else out.push(`<a href="mailto:${esc(m[6])}">${esc(m[6])}</a>`);
    last = re.lastIndex;
  }
  out.push(esc(text.slice(last)));
  return out.join("");
}

// Links to our own pages stay relative, so they work on any deployment URL.
const link = (u) => (u.startsWith(SITE) ? u.slice(SITE.length) || "/" : u);

export function render(md) {
  const html = [];
  let list = null, para = [];
  const flush = () => {
    if (para.length) { html.push(`<p>${inline(para.join(" "))}</p>`); para = []; }
    if (list) { html.push(`</${list}>`); list = null; }
  };
  for (const raw of md.split("\n")) {
    const line = raw.trimEnd();
    if (line === "---") break; // the Markdown footer; HTML pages have their own
    let m;
    if (!line.trim()) { flush(); continue; }
    if ((m = /^(#{1,2}) (.*)$/.exec(line))) { flush(); html.push(`<h${m[1].length}>${inline(m[2])}</h${m[1].length}>`); continue; }
    if ((m = /^> (.*)$/.exec(line))) { flush(); html.push(`<blockquote><p>${inline(m[1])}</p></blockquote>`); continue; }
    if ((m = /^(- |\d+\. )(.*)$/.exec(line))) {
      const kind = m[1] === "- " ? "ul" : "ol";
      if (para.length) { html.push(`<p>${inline(para.join(" "))}</p>`); para = []; }
      if (list !== kind) { if (list) html.push(`</${list}>`); html.push(`<${kind}>`); list = kind; }
      html.push(`<li>${inline(m[2])}</li>`);
      continue;
    }
    if (list) { html.push(`</${list}>`); list = null; }
    para.push(line.trim());
  }
  flush();
  return html.join("\n");
}

function description(md) {
  const first = md.split("\n").find((l) => l.trim() && !l.startsWith("#") && !/^last updated/i.test(l)) || "";
  const text = first.replace(/^> /, "").replace(/\*\*|`/g, "").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");
  return text.length > 158 ? text.slice(0, 155).replace(/\s+\S*$/, "") + "…" : text;
}

